"""Пул інгредієнтів: 10 стихій x 20 форм = 200 унікальних."""
ESSENCES = {
    "fire": "Вогню", "water": "Води", "earth": "Землі", "air": "Повітря",
    "light": "Світла", "shadow": "Тіні", "life": "Життя", "death": "Смерті",
    "mind": "Розуму", "spirit": "Духу",
}
FORMS = [
    "Корінь", "Листок", "Пелюстка", "Гриб", "Ягода", "Насіння", "Кора",
    "Мох", "Квітка", "Смола", "Лишайник", "Паросток", "Шипшина", "Стебло",
    "Шишка", "Сік", "Спора", "Гілка", "Плід", "Бульба",
]

INGREDIENTS = {}
for _e, _gen in ESSENCES.items():
    for _f in FORMS:
        _id = f"{_e}_{FORMS.index(_f)}"
        INGREDIENTS[_id] = {"name": f"{_f} {_gen}", "essence": _e}

if len(INGREDIENTS) < 200:
    raise RuntimeError("Пул інгредієнтів менший за 200!")
